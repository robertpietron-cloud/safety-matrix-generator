"""Command line interface: ``safety-matrix`` / ``python -m safety_matrix``."""
from __future__ import annotations

import argparse
import datetime as _dt
import sys

from . import __version__

HEADER = """# =============================================================================
# Project : Safety Matrix Generator (GuardLogix SafetyTask -> Cause & Effect)
# File    : {file}
# Author  : {author}
# Revision: 1.0.0 ({date})
# Changes :
#   1.0.0 ({date}) - Configuration skeleton generated by safety-matrix
#                        init-config {version} from {src}.
# =============================================================================
# Edit zone / group names, device types and descriptions, then run:
#   safety-matrix analyze {src} -c {file} -o matrix.xlsx
# Texts may be plain strings or dictionaries per language: {{pl: ..., en: ...}}.
"""


def _langs(s):
    return [x.strip().lower() for x in s.split(',') if x.strip()] if s else None


def cmd_analyze(a) -> int:
    from .pipeline import run
    out = a.output or (a.input.rsplit('.', 1)[0] + '_SafetyMatrix.xlsx')
    s = run(a.input, out, a.config, _langs(a.lang), a.default_lang, a.json, a.author, a.revision)
    cells = ', '.join(f'{k} {v}' for k, v in s['cells'].items())
    print(f"{s['controller']}: {s['devices']} devices, {s['effects']} outputs; cells: {cells}")
    print(f"report: {s['alarm']} critical alarm(s), {s['dead']} dead item(s), {s['verify']} item(s) to verify")
    print(f'written: {out}' + (f' and {a.json}' if a.json else ''))
    if a.fail_on_alarm and s['alarm']:
        return 2
    return 0


def cmd_init(a) -> int:
    import yaml
    from .analysis import Analysis
    from .config import Config, Layout
    from .i18n import Tr
    from .parsers import load_project
    p = load_project(a.input)
    A = Analysis(p)
    langs = _langs(a.lang) or ['en']
    tr = Tr(langs)
    ly = Layout(A, Config(languages=langs, default_language=langs[0]), tr)
    data = {
        'document': {'title': f'SAFETY MATRIX – {p.controller} (SafetyTask)', 'author': a.author or '', 'revision': '1.0',
                     'date': _dt.date.today().isoformat(), 'revisions': []},
        'languages': langs, 'default_language': langs[0],
        'analysis': {'info_effects': [], 'include_effects': [], 'exclude_effects': [], 'crtl_priority_ms': 1000},
        'zones': [{'name': z.name.first(), 'devices': list(z.devices)} for z in ly.zones],
        'effect_groups': [{'name': g.name.first(), 'effects': list(g.effects)} for g in ly.groups],
        'devices': {t: {'type': A.devices[t].type, 'description': ly.dev_desc[t].first()} for t in ly.ordered_devices()},
        'effects': {k: {'description': ly.eff_desc[k].first(), 'valve': False} for k in ly.ordered_effects()},
    }

    class D(yaml.SafeDumper):
        pass
    D.add_representer(str, lambda d, s: d.represent_scalar('tag:yaml.org,2002:str', s))
    out = a.output or 'config.yaml'
    txt = HEADER.format(file=out, author=a.author or 'Robert Pietroń', date=_dt.date.today().isoformat(), version=__version__,
                        src=a.input) + yaml.dump(data, Dumper=D, allow_unicode=True, sort_keys=False, width=140)
    with open(out, 'w', encoding='utf-8') as f:
        f.write(txt)
    print(f'written: {out} ({len(ly.zones)} zones, {len(A.devices)} devices, {len(ly.ordered_effects())} outputs)')
    return 0


def cmd_dump(a) -> int:
    from .parsers import load_project
    p = load_project(a.input)
    task = p.safety_task
    print(f'{p.controller} {p.processor} {p.software_version}; safety task: '
          f"{task.name + f' {task.rate_ms:g} ms' if task else '—'}; SafetyTagMap: {p.safety_tag_map or '—'}")
    for prog in p.safety_programs():
        for r in prog.routines.values():
            if a.routine and r.name != a.routine:
                continue
            print(f'ROUTINE {prog.name}/{r.name} ({len(r.rungs)} rungs{", protected" if r.protected else ""})')
            for rung in r.rungs:
                if rung.comment.strip():
                    print(f'  RC{rung.number}: ' + ' '.join(rung.comment.split()))
                print(f'  R{rung.number}: {rung.text}')
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog='safety-matrix', description='Safety Matrix (Cause & Effect) generator for GuardLogix SafetyTask '
                                                                  '(Studio 5000 L5K / L5X exports).')
    ap.add_argument('--version', action='version', version=f'safety-matrix-generator {__version__} (Robert Pietroń)')
    sub = ap.add_subparsers(dest='cmd', required=True)
    p1 = sub.add_parser('analyze', help='analyse an export and write the Excel workbook')
    p1.add_argument('input', help='.L5K, .L5X, or a .docx/.txt containing an L5K export')
    p1.add_argument('-c', '--config', help='YAML project configuration (optional)')
    p1.add_argument('-o', '--output', help='output .xlsx (default: <input>_SafetyMatrix.xlsx)')
    p1.add_argument('--lang', help='languages, comma separated: pl,en,fr,da (default from config: all four)')
    p1.add_argument('--default-lang', help='language shown when the workbook opens')
    p1.add_argument('--json', help='also write the analysis as JSON')
    p1.add_argument('--author', help='document author (overrides the config)')
    p1.add_argument('--revision', help='document revision (overrides the config)')
    p1.add_argument('--fail-on-alarm', action='store_true', help='exit code 2 when critical alarms are found (CI)')
    p1.set_defaults(fn=cmd_analyze)
    p2 = sub.add_parser('init-config', help='write a configuration skeleton (zones, groups, descriptions) to edit')
    p2.add_argument('input')
    p2.add_argument('-o', '--output', help='output YAML (default: config.yaml)')
    p2.add_argument('--lang', help='languages for the skeleton (default: en)')
    p2.add_argument('--author', help='author written into the file header')
    p2.set_defaults(fn=cmd_init)
    p3 = sub.add_parser('dump', help='print the parsed safety routines (check of the parser)')
    p3.add_argument('input')
    p3.add_argument('--routine', help='only this routine')
    p3.set_defaults(fn=cmd_dump)
    a = ap.parse_args(argv)
    return a.fn(a)


if __name__ == '__main__':
    sys.exit(main())
